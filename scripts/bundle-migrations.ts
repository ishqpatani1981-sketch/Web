/**
 * Embeds drizzle/*.sql into lib/db/migrations.generated.ts so the app can migrate the
 * embedded demo database at runtime (including on serverless platforms where the
 * drizzle/ folder is not traced into the bundle). Run automatically by `npm run db:generate`.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = join(process.cwd(), 'drizzle');
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
const migrations = files.map((name) => ({
  name,
  statements: readFileSync(join(dir, name), 'utf8')
    .split('--> statement-breakpoint')
    .map((s) => s.trim())
    .filter(Boolean),
}));

const out = `// AUTO-GENERATED by scripts/bundle-migrations.ts — do not edit by hand.
export const MIGRATIONS: { name: string; statements: string[] }[] = ${JSON.stringify(migrations, null, 2)};
`;
writeFileSync(join(process.cwd(), 'lib/db/migrations.generated.ts'), out);
console.log(`Bundled ${migrations.length} migration(s).`);
